    let k = nights[today] ? today : addDays(today, -1), streak = 0;
    while (isDry(k)) { streak++; k = addDays(k, -1); }
    // best dry streak
    let best = 0, run = 0, prev = null;
    Object.keys(nights).sort().forEach(key => {
      if (isDry(key)) { run = (prev && addDays(prev, 1) === key && run > 0) ? run + 1 : 1; best = Math.max(best, run); }
      else run = 0;
      prev = key;
    });
    const inLast = (key, days) => key > addDays(today, -days) && key <= today;
    const nk = Object.keys(nights);
    const wet7 = nk.filter(x => inLast(x, 7) && nights[x].night.wet).length;
    const wet28 = nk.filter(x => inLast(x, 28) && nights[x].night.wet).length;
